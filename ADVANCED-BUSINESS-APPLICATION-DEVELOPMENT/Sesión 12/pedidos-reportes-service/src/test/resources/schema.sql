CREATE TABLE pedido (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente VARCHAR(120) NOT NULL,
    producto_codigo VARCHAR(30) NOT NULL,
    producto_nombre VARCHAR(120) NOT NULL,
    precio_unitario DECIMAL(12, 2) NOT NULL,
    cantidad INTEGER NOT NULL,
    total DECIMAL(12, 2) NOT NULL,
    fecha TIMESTAMP NOT NULL,
    revisado BOOLEAN NOT NULL DEFAULT FALSE,
    estado_revision VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',
    CONSTRAINT chk_pedido_estado_revision
        CHECK (estado_revision IN ('PENDIENTE', 'ACEPTADO', 'RECHAZADO'))
);

CREATE TABLE pedido_revision (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id BIGINT NOT NULL UNIQUE,
    observacion VARCHAR(500) NOT NULL,
    revisado_por VARCHAR(100) NOT NULL,
    fecha_revision TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_pedido_revision_pedido FOREIGN KEY (pedido_id) REFERENCES pedido (id)
);
